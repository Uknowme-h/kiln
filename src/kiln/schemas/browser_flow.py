"""Structured browser click-through plan for the host Playwright gate.

Authored by the test author (``docs/browser-flows.json``) or generated by a
heuristic fallback. Not free-form MCP — a small FlowPlan the companion runs
deterministically after suite green.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field, model_validator

StepKind = Literal[
    "goto",
    "click",
    "fill",
    "expect_visible",
    "expect_text",
    "expect_url",
    "expect_console_clean",
]


class FlowStep(BaseModel):
    kind: StepKind
    # goto / expect_url
    url: str | None = None
    # click / fill / expect_visible: role+name or CSS
    role: str | None = None
    name: str | None = None
    selector: str | None = None
    # fill
    value: str | None = None
    # expect_text / expect_visible text match
    text: str | None = None
    timeout_ms: int = Field(default=5000, ge=100, le=60_000)

    @model_validator(mode="after")
    def shape_matches_kind(self) -> FlowStep:
        kind = self.kind
        if kind == "goto" and not self.url:
            raise ValueError("goto requires url")
        if kind == "expect_url" and not self.url:
            raise ValueError("expect_url requires url")
        if kind == "fill" and self.value is None:
            raise ValueError("fill requires value")
        if kind == "expect_text" and not self.text:
            raise ValueError("expect_text requires text")
        if kind in ("click", "fill", "expect_visible") and not (
            self.selector or (self.role and self.name) or self.text
        ):
            raise ValueError(f"{kind} needs selector, role+name, or text")
        return self


class Flow(BaseModel):
    id: str = Field(min_length=1)
    name: str = Field(min_length=1)
    steps: list[FlowStep] = Field(min_length=1)


class FlowPlan(BaseModel):
    base_url: str = ""
    flows: list[Flow] = Field(min_length=1)


