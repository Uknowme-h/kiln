"""The API contract as the two developers' shared source of truth.

API-first teams agree on a spec (OpenAPI / JSON Schema) before coding, generate
types from it so both sides import the same shapes, review every change to it,
and run contract checks in CI. This module is that toolkit for Kiln:

- ``contract_json``      the language-neutral contract file;
- ``types_targets``      where each root's generated types module lives;
- ``render_types``       TypeScript / Python / JSDoc types from the contract;
- ``contract_digest``    one line per route with its exact fields;
- ``conformance_gaps``   contract fields missing from the files a developer wrote;
- ``apply_change``       a proposed route change, with a human-readable diff;
- ``change_conflicts``   why a change would break the already-written suite.

Everything here is pure (no I/O), so the orchestrator decides when to read,
write and announce.
"""

from __future__ import annotations

import json
import re

from kiln.schemas.tasks import BODY_METHODS, Contract, ContractRoute, FieldSpec

CONTRACT_JSON = "docs/api-contract.json"
HEADER = (
    "Generated by Kiln from the approved API contract (docs/api-contract.json). "
    "Do not edit by hand: propose_contract_change updates the contract and "
    "regenerates this file."
)

# Where each framework's toolchain already looks, so the import needs no config.
_TYPES_PATHS = {
    "vite_react": ("src/contract.ts", "ts"),
    "nestjs": ("src/contract.ts", "ts"),
    "nextjs": ("lib/contract.ts", "ts"),
    "express": ("src/contract.js", "js"),
    "fastapi": ("app/contract.py", "py"),
    "flask": ("app/contract.py", "py"),
}

_FRONTEND_SUFFIXES = (".tsx", ".jsx", ".vue", ".svelte", ".html")


def api_routes(contract: Contract | None) -> list[ContractRoute]:
    return [route for route in (contract.routes if contract else []) if route.kind == "api"]


def contract_json(contract: Contract) -> str:
    return json.dumps(contract.model_dump(), indent=2) + "\n"


def types_targets(spec, contract: Contract | None) -> list[tuple[str, str]]:
    """(workspace path, language) of the types module for every root."""
    if not api_routes(contract):
        return []
    roots = [(r.path, r.framework) for r in (spec.roots or []) if r.framework] if spec else []
    if not roots and spec is not None and len(spec.frameworks or []) == 1:
        roots = [(".", spec.frameworks[0])]
    targets: list[tuple[str, str]] = []
    for root, framework in roots:
        if framework not in _TYPES_PATHS:
            continue
        rel, language = _TYPES_PATHS[framework]
        prefix = "" if root in ("", ".") else root.strip().rstrip("/") + "/"
        path = prefix + rel
        if path not in [t[0] for t in targets]:
            targets.append((path, language))
    return targets


# ── names and types ─────────────────────────────────────────────────────────


def _pascal(text: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", text)
    return "".join(word[:1].upper() + word[1:] for word in words)


def route_type_name(route: ContractRoute) -> str:
    """`GET /api/notes/{id}` → `GetApiNotesById`."""
    parts = [route.method.lower()]
    for segment in route.path.strip("/").split("/"):
        if not segment:
            continue
        param = re.fullmatch(r"\{(\w+)\}|:(\w+)|\[(\w+)\]", segment)
        parts.append(f"by {next(g for g in param.groups() if g)}" if param else segment)
    name = _pascal(" ".join(parts))
    return name if name and not name[0].isdigit() else f"Route{name}"


def _named_routes(contract: Contract) -> list[tuple[str, ContractRoute]]:
    seen: dict[str, int] = {}
    named = []
    for route in api_routes(contract):
        base = route_type_name(route)
        seen[base] = seen.get(base, 0) + 1
        named.append((base if seen[base] == 1 else f"{base}{seen[base]}", route))
    return named


_SCALARS = {
    "string": ("string", "str"), "str": ("string", "str"), "text": ("string", "str"),
    "email": ("string", "str"), "uuid": ("string", "str"), "url": ("string", "str"),
    "date": ("string", "str"), "datetime": ("string", "str"), "date-time": ("string", "str"),
    "timestamp": ("string", "str"), "integer": ("number", "int"), "int": ("number", "int"),
    "number": ("number", "float"), "float": ("number", "float"), "double": ("number", "float"),
    "boolean": ("boolean", "bool"), "bool": ("boolean", "bool"),
    "object": ("Record<string, unknown>", "dict[str, Any]"),
    "json": ("Record<string, unknown>", "dict[str, Any]"),
    "dict": ("Record<string, unknown>", "dict[str, Any]"),
    "any": ("unknown", "Any"), "null": ("null", "None"),
}  # fmt: skip


def _map_type(raw: str, language: str) -> tuple[str, bool]:
    """(type expression, known?) for TypeScript ('ts') or Python ('py')."""
    text = raw.strip()
    low = text.lower()
    inner = None
    if low.endswith("[]"):
        inner = text[:-2]
    else:
        match = re.fullmatch(r"(?:array|list)\s*[<\[]\s*(.+?)\s*[>\]]", text, re.IGNORECASE)
        if match:
            inner = match.group(1)
    if inner is not None:
        mapped, known = _map_type(inner, language)
        return (f"{mapped}[]" if language == "ts" else f"list[{mapped}]"), known
    if low in _SCALARS:
        ts, py = _SCALARS[low]
        return (ts if language == "ts" else py), True
    return ("unknown" if language == "ts" else "Any"), False


def _ts_key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][\w$]*", name) else json.dumps(name)


def _ts_interface(name: str, fields: list[FieldSpec], doc: str) -> list[str]:
    lines = [f"/** {doc} */", f"export interface {name} {{"]
    for field in fields:
        mapped, known = _map_type(field.type, "ts")
        note = "" if known else f" // contract type: {field.type}"
        comment = f"  /** {field.description} */\n" if field.description else ""
        lines.append(f"{comment}  {_ts_key(field.name)}{'' if field.required else '?'}: {mapped};{note}")
    lines.append("}")
    return lines


def _py_typed_dict(name: str, fields: list[FieldSpec], doc: str) -> list[str]:
    required = [f.name for f in fields if f.required]
    body = []
    for field in fields:
        mapped, known = _map_type(field.type, "py")
        note = "" if known else f"  # contract type: {field.type}"
        body.append(f"        {json.dumps(field.name)}: {mapped},{note}")
    return [
        f"# {doc}",
        f"# required keys: {', '.join(required) or 'none'}",
        f"{name} = TypedDict(",
        f"    {json.dumps(name)},",
        "    {",
        *body,
        "    },",
        "    total=False,",
        ")",
        f"{_upper_snake(name)}_REQUIRED = {tuple(required)!r}",
    ]


def _upper_snake(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


def render_types(contract: Contract, language: str) -> str:
    """Types-only module for one language ('ts', 'py' or 'js')."""
    named = _named_routes(contract)
    if language == "ts":
        out = [f"// {HEADER}", ""]
        for name, route in named:
            doc = f"{route.method.upper()} {route.path} -> {route.status}"
            if route.request_fields:
                out += _ts_interface(f"{name}Request", route.request_fields, f"{doc} request body")
                out.append("")
            if route.response_fields:
                out += _ts_interface(f"{name}Response", route.response_fields, f"{doc} response body")
                out.append("")
        if contract.error_shape:
            out += _ts_interface("ApiError", contract.error_shape, "Error body every api route returns")
            out.append("")
        out.append("export const API_ROUTES = {")
        for name, route in named:
            key = name[:1].lower() + name[1:]
            out.append(
                f"  {key}: {{ method: {json.dumps(route.method.upper())}, path: "
                f"{json.dumps(route.path)}, status: {route.status}, auth: "
                f"{'true' if route.auth else 'false'} }},"
            )
        out.append("} as const;")
        return "\n".join(out) + "\n"
    if language == "py":
        out = [f'"""{HEADER}"""', "", "from typing import Any, TypedDict", ""]
        for name, route in named:
            doc = f"{route.method.upper()} {route.path} -> {route.status}"
            if route.request_fields:
                out += _py_typed_dict(f"{name}Request", route.request_fields, f"{doc} request body")
                out.append("")
            if route.response_fields:
                out += _py_typed_dict(f"{name}Response", route.response_fields, f"{doc} response body")
                out.append("")
        if contract.error_shape:
            out += _py_typed_dict("ApiError", contract.error_shape, "Error body every api route returns")
            out.append("")
        out.append("API_ROUTES = {")
        for name, route in named:
            out.append(
                f"    {json.dumps(name)}: {{\"method\": {json.dumps(route.method.upper())}, "
                f"\"path\": {json.dumps(route.path)}, \"status\": {route.status}, "
                f"\"auth\": {route.auth}}},"
            )
        out.append("}")
        return "\n".join(out) + "\n"
    # JSDoc only: no runtime code, so it is valid as CommonJS and as an ES module
    example = next(
        (f"{n}{'Request' if r.request_fields else 'Response'}" for n, r in named
         if r.request_fields or r.response_fields),
        "ApiError",
    )  # fmt: skip
    out = [f"// {HEADER}", f"// Use: /** @type {{import('./contract.js').{example}}} */", ""]
    for name, route in named:
        for suffix, fields in (("Request", route.request_fields), ("Response", route.response_fields)):
            if not fields:
                continue
            members = ", ".join(
                f"{_ts_key(f.name)}{'' if f.required else '?'}: {_map_type(f.type, 'ts')[0]}"
                for f in fields
            )
            out.append(f"/** {route.method.upper()} {route.path} -> {route.status} */")
            out.append(f"/** @typedef {{{{ {members} }}}} {name}{suffix} */")
    if contract.error_shape:
        members = ", ".join(
            f"{_ts_key(f.name)}{'' if f.required else '?'}: {_map_type(f.type, 'ts')[0]}"
            for f in contract.error_shape
        )
        out.append(f"/** @typedef {{{{ {members} }}}} ApiError */")
    return "\n".join(out) + "\n"


def contract_digest(contract: Contract) -> str:
    """One line per route with its exact fields — the reminder's compact form."""
    lines = []
    for route in contract.routes:
        line = f"{route.method.upper()} {route.path}"
        if route.kind == "page":
            lines.append(f"{line} (page)")
            continue
        if route.request_fields:
            line += " " + _inline(route.request_fields)
        line += f" -> {route.status}"
        if route.response_fields:
            line += " " + _inline(route.response_fields)
        lines.append(line)
    lines.extend(contract.modules)
    if contract.shared_files:
        lines.append("scaffold owns: " + ", ".join(contract.shared_files))
    return "\n".join(lines)


def _inline(fields: list[FieldSpec]) -> str:
    return "{" + ", ".join(f"{f.name}{'' if f.required else '?'}: {f.type}" for f in fields) + "}"


# ── conformance: did the developer build what the contract says? ───────────


def _literal_segments(path: str) -> list[str]:
    return [
        s for s in path.strip("/").split("/")
        if s and not re.fullmatch(r"\{\w+\}|:\w+|\[\.*\w+\]|\*", s)
    ]  # fmt: skip


def _implements(route: ContractRoute, path: str, text: str) -> bool:
    """Static guess: does this file implement (or call) the route?"""
    segments = _literal_segments(route.path)
    if not segments:
        return False
    norm = path.replace("\\", "/")
    # file-based routing: app/api/notes/route.ts, pages/api/notes.ts
    joined = "/".join(segments)
    if joined in norm and re.search(r"(^|/)(route|index)\.\w+$|(^|/)pages/api/", norm):
        return True
    last = re.escape(segments[-1])
    if not re.search(rf"""["'`][^"'`\n]*/{last}(?:/|["'`?])""", text):
        return False
    return re.search(rf"\b{route.method.lower()}\b", text.lower()) is not None


def _is_frontend(path: str) -> bool:
    norm = path.replace("\\", "/").lower()
    if "/api/" in norm or norm.startswith("api/"):
        return False
    return norm.endswith(_FRONTEND_SUFFIXES) or any(
        part in norm for part in ("/components/", "/pages/", "/views/", "frontend/")
    )


def conformance_gaps(files: dict[str, str], contract: Contract | None) -> list[str]:
    """Contract fields absent from the files that implement or call a route.

    Backend files must mention every request and response field of a route
    they implement; frontend files must send every required request field of
    a route they call. A static heuristic: false alarms are possible (fields
    defined in another file), so callers treat it as a warning, never a wall.
    """
    gaps: list[str] = []
    for route in api_routes(contract):
        backend = {p: t for p, t in files.items() if not _is_frontend(p) and _implements(route, p, t)}
        frontend = {p: t for p, t in files.items() if _is_frontend(p) and _implements(route, p, t)}
        name = f"{route.method.upper()} {route.path}"
        if backend:
            text = "\n".join(backend.values())
            missing = [
                f.name for f in (*route.request_fields, *route.response_fields)
                if not re.search(rf"\b{re.escape(f.name)}\b", text)
            ]  # fmt: skip
            if missing:
                gaps.append(f"{name} ({', '.join(sorted(backend))}) never mentions {', '.join(missing)}")
        if frontend and route.method.upper() in BODY_METHODS:
            text = "\n".join(frontend.values())
            missing = [
                f.name for f in route.request_fields
                if f.required and not re.search(rf"\b{re.escape(f.name)}\b", text)
            ]  # fmt: skip
            if missing:
                gaps.append(
                    f"{name} is called from {', '.join(sorted(frontend))} without the required "
                    f"field(s) {', '.join(missing)}"
                )
    return gaps


# ── changes ─────────────────────────────────────────────────────────────────


def find_route(contract: Contract | None, method: str, path: str) -> ContractRoute | None:
    for route in contract.routes if contract else []:
        if route.method.upper() == method.upper() and route.path == path:
            return route
    return None


def apply_change(
    contract: Contract | None,
    method: str,
    path: str,
    *,
    request_fields: list[FieldSpec] | None,
    response_fields: list[FieldSpec] | None,
    status: int | None,
) -> tuple[Contract, ContractRoute | None, ContractRoute, str]:
    """(new contract, old route, new route, summary). ``None`` keeps a part as is."""
    base = contract or Contract()
    old = find_route(base, method, path)
    template = old or ContractRoute(method=method.upper(), path=path)
    new = template.model_copy(
        update={
            "request_fields": list(request_fields) if request_fields is not None else template.request_fields,
            "response_fields": list(response_fields) if response_fields is not None else template.response_fields,
            "status": status if status is not None else template.status,
        }
    )
    routes = [new if r is old else r for r in base.routes] if old else [*base.routes, new]
    return base.model_copy(update={"routes": routes}), old, new, describe_change(old, new)


def describe_change(old: ContractRoute | None, new: ContractRoute) -> str:
    name = f"{new.method.upper()} {new.path}"
    if old is None:
        return f"new route {name}: request {_inline(new.request_fields)} -> {new.status} {_inline(new.response_fields)}"
    parts = []
    for label, before, after in (
        ("request", old.request_fields, new.request_fields),
        ("response", old.response_fields, new.response_fields),
    ):
        was = {f.name: f for f in before}
        now = {f.name: f for f in after}
        added = [f"{n}: {now[n].type}{'' if now[n].required else ' (optional)'}" for n in now if n not in was]
        removed = [n for n in was if n not in now]
        changed = [
            f"{n} {was[n].type}{'' if was[n].required else '?'} → {now[n].type}{'' if now[n].required else '?'}"
            for n in now
            if n in was and (was[n].type != now[n].type or was[n].required != now[n].required)
        ]
        if added:
            parts.append(f"{label} adds {', '.join(added)}")
        if removed:
            parts.append(f"{label} removes {', '.join(removed)}")
        if changed:
            parts.append(f"{label} changes {', '.join(changed)}")
    if old.status != new.status:
        parts.append(f"status {old.status} → {new.status}")
    return f"{name}: " + ("; ".join(parts) if parts else "no change")


def change_conflicts(old: ContractRoute | None, new: ContractRoute, suite_text: str) -> list[str]:
    """Why a change would break the suite that was written from the contract.

    The suite is the independent judge: a field or status it asserts on may
    not disappear from under it. Additions are always compatible.
    """
    if old is None:
        return []
    problems = []
    for label, before, after in (
        ("request", old.request_fields, new.request_fields),
        ("response", old.response_fields, new.response_fields),
    ):
        names = {f.name for f in after}
        for field in before:
            if field.name not in names and re.search(rf"\b{re.escape(field.name)}\b", suite_text):
                problems.append(f"it removes {label} field '{field.name}', which the tests use")
    if old.status != new.status and old.path in suite_text:
        problems.append(f"it changes the status of {old.path}, which the tests call")
    return problems
